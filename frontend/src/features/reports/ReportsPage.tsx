/**
 * FinPilot AI — Reports Page
 */

import React from "react";
import { motion } from "framer-motion";
import { useQuery } from "@tanstack/react-query";
import { TrendingUp, FileText, Download, Calendar, Bot, Zap, Plus } from "lucide-react";
import { reportsAPI } from "@/lib/api";

const containerVariants = {
  hidden: { opacity: 0 },
  visible: { opacity: 1, transition: { staggerChildren: 0.06 } },
};
const itemVariants = {
  hidden: { opacity: 0, y: 16 },
  visible: { opacity: 1, y: 0 },
};

const REPORT_TYPES = [
  { type: "financial",   label: "Financial Analysis",   icon: "📊", color: "from-blue-500 to-blue-600",   desc: "Comprehensive P&L, balance sheet, and cash flow analysis" },
  { type: "risk",        label: "Risk Assessment",       icon: "⚠️", color: "from-amber-500 to-amber-600", desc: "Multi-dimensional risk scoring and mitigation strategies" },
  { type: "compliance",  label: "Compliance Report",     icon: "✅", color: "from-green-500 to-green-600", desc: "IFRS, SOX, Basel III, and regulatory compliance status" },
  { type: "fraud",       label: "Fraud Investigation",   icon: "🔍", color: "from-red-500 to-red-600",    desc: "Anomaly detection and forensic accounting analysis" },
  { type: "investment",  label: "Investment Analysis",   icon: "💰", color: "from-violet-500 to-violet-600", desc: "DCF valuation, portfolio recommendations, ESG scoring" },
  { type: "forecast",    label: "Financial Forecast",    icon: "📈", color: "from-teal-500 to-teal-600",   desc: "Revenue projections, scenario analysis, and modeling" },
];

export default function ReportsPage() {
  const { data, isLoading } = useQuery({
    queryKey: ["reports"],
    queryFn: () => reportsAPI.list().then((r) => r.data),
  });

  return (
    <div className="p-6 space-y-6">
      <motion.div initial={{ opacity: 0, y: -10 }} animate={{ opacity: 1, y: 0 }} className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold text-foreground">AI-Generated Reports</h1>
          <p className="text-sm text-muted-foreground mt-0.5">Board-ready reports generated by your AI agent workforce</p>
        </div>
        <motion.button
          whileHover={{ scale: 1.02 }}
          whileTap={{ scale: 0.98 }}
          className="flex items-center gap-2 px-4 py-2 bg-primary rounded-lg text-primary-foreground text-sm font-medium shadow-glow-sm"
        >
          <Plus size={15} />
          Generate Report
        </motion.button>
      </motion.div>

      {/* Report Type Cards */}
      <motion.div variants={containerVariants} initial="hidden" animate="visible" className="grid grid-cols-2 md:grid-cols-3 gap-4">
        {REPORT_TYPES.map((rt) => (
          <motion.div
            key={rt.type}
            variants={itemVariants}
            whileHover={{ y: -3, scale: 1.01 }}
            className="glass-card cursor-pointer group"
          >
            <div className={`w-10 h-10 rounded-xl bg-gradient-to-br ${rt.color} flex items-center justify-center text-xl mb-3`}>
              {rt.icon}
            </div>
            <h3 className="text-sm font-semibold text-foreground mb-1">{rt.label}</h3>
            <p className="text-xs text-muted-foreground">{rt.desc}</p>
            <motion.div
              initial={{ opacity: 0 }}
              whileHover={{ opacity: 1 }}
              className="mt-3 text-xs text-primary flex items-center gap-1"
            >
              <Zap size={11} />
              Generate with AI
            </motion.div>
          </motion.div>
        ))}
      </motion.div>

      {/* Existing Reports */}
      <div>
        <h2 className="text-sm font-semibold text-foreground mb-3 flex items-center gap-2">
          <FileText size={15} className="text-muted-foreground" />
          Recent Reports
        </h2>

        {isLoading ? (
          <div className="space-y-3">
            {[...Array(3)].map((_, i) => <div key={i} className="h-16 rounded-xl bg-secondary animate-pulse" />)}
          </div>
        ) : (data?.reports || []).length === 0 ? (
          <div className="text-center py-16 glass rounded-xl">
            <div className="text-4xl mb-3">📋</div>
            <p className="text-foreground font-medium">No reports yet</p>
            <p className="text-muted-foreground text-sm mt-1">
              Generate your first AI report by selecting a type above
            </p>
          </div>
        ) : (
          <div className="space-y-3">
            {(data?.reports || []).map((report: any) => (
              <motion.div
                key={report.id}
                initial={{ opacity: 0, x: -10 }}
                animate={{ opacity: 1, x: 0 }}
                className="glass rounded-xl p-4 flex items-center gap-4"
              >
                <div className="w-9 h-9 rounded-lg bg-secondary flex items-center justify-center">
                  <TrendingUp size={16} className="text-primary" />
                </div>
                <div className="flex-1">
                  <div className="text-sm font-medium text-foreground">{report.title}</div>
                  <div className="text-xs text-muted-foreground flex items-center gap-2 mt-0.5">
                    <Calendar size={10} />
                    {new Date(report.created_at).toLocaleDateString()}
                    {report.confidence_score && (
                      <span className="text-primary">{(report.confidence_score * 100).toFixed(0)}% confidence</span>
                    )}
                  </div>
                </div>
                <div className="flex items-center gap-2">
                  {report.agents_used?.length > 0 && (
                    <span className="agent-badge">{report.agents_used.length} agents</span>
                  )}
                  <button className="w-7 h-7 flex items-center justify-center rounded-lg hover:bg-secondary text-muted-foreground hover:text-foreground transition-colors">
                    <Download size={13} />
                  </button>
                </div>
              </motion.div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
